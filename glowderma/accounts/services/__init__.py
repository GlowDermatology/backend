"""The accounts module's service layer (AGENTS.md "Architecture rules": transactional writes).

This package is the stable entry point: callers import ``from glowderma.accounts import services`` and call
``services.<name>``; the code lives in the submodules, one subject each:

- ``common``: ``hashing`` (stored digests) and ``revocation`` (session tombstones, revoke, audit).
- ``customer``: ``locks`` (the row-lock repository), ``devices``, ``auth_sessions``, ``device_registration``,
  ``refresh``, ``profile``, ``addresses``, ``identities`` and ``lifecycle``.
- ``otp``: ``channels``, ``targets``, ``limits``, ``issuance`` and ``verification`` of one-time codes.
- ``staff``: ``messages``, ``locks``, ``auth_sessions``, ``credentials``, ``password_links``, ``members``,
  ``social`` and ``two_factor``.

Submodules import their siblings as modules (``locks.lock_customer(...)``), never this facade, so a call made
inside the package is patched on the submodule that defines the name; a call made from another app through
``services.<name>`` is patched here. Helpers shared between submodules are not re-exported.
"""

